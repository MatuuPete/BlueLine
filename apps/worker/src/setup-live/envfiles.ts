// Rendering and re-reading deploy/vercel.env and deploy/github-secrets.txt.

export const DEFAULT_BUDGET = '2500';

/** KEY=value lines; blank lines and `#` comments are ignored. */
export function parseEnvText(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf('=');
    if (i <= 0) continue;
    out[t.slice(0, i).trim()] = t.slice(i + 1).trim();
  }
  return out;
}

export interface GeneratedSecrets {
  authSecret: string;
  backupPassphrase: string;
}

/** Reuse the secrets of a previous run unless `rotate`; otherwise generate with `make`. */
export function resolveSecrets(
  existingVercel: Record<string, string>,
  existingGithub: Record<string, string>,
  rotate: boolean,
  make: { authSecret: () => string; backupPassphrase: () => string },
): GeneratedSecrets & { reused: { authSecret: boolean; backupPassphrase: boolean } } {
  const oldAuth = rotate ? undefined : existingVercel.AUTH_SECRET || undefined;
  const oldBackup = rotate ? undefined : existingGithub.BACKUP_PASSPHRASE || undefined;
  return {
    authSecret: oldAuth ?? make.authSecret(),
    backupPassphrase: oldBackup ?? make.backupPassphrase(),
    reused: { authSecret: oldAuth !== undefined, backupPassphrase: oldBackup !== undefined },
  };
}

export interface OAuthPair {
  id: string;
  secret: string;
}

export interface DeployValues {
  webUrl: string;
  workerUrl: string;
  ownerUrl: string;
  directUrl: string;
  sgoApiKey: string;
  allowedEmails: string;
  github?: OAuthPair;
  google?: OAuthPair;
  budget?: string;
}

export function normalizeEmailList(raw: string): string {
  return raw
    .split(',')
    .map((e) => e.trim().toLowerCase())
    .filter(Boolean)
    .join(',');
}

export function renderVercelEnv(v: DeployValues, s: GeneratedSecrets): string {
  const lines = [
    '# Paste this whole file into Vercel > Project > Settings > Environment Variables.',
    '# Generated by `corepack pnpm setup:live`. Contains secrets: never commit it.',
    `DATABASE_URL=${v.webUrl}`,
    `AUTH_SECRET=${s.authSecret}`,
    `ALLOWED_EMAILS=${v.allowedEmails}`,
    v.github ? `AUTH_GITHUB_ID=${v.github.id}` : '# AUTH_GITHUB_ID=<from your GitHub OAuth app>',
    v.github ? `AUTH_GITHUB_SECRET=${v.github.secret}` : '# AUTH_GITHUB_SECRET=',
    v.google ? `AUTH_GOOGLE_ID=${v.google.id}` : '# AUTH_GOOGLE_ID=<from your Google OAuth client>',
    v.google ? `AUTH_GOOGLE_SECRET=${v.google.secret}` : '# AUTH_GOOGLE_SECRET=',
    'ODDS_PROVIDER=sgo',
    `ODDS_MONTHLY_BUDGET=${v.budget ?? DEFAULT_BUDGET}`,
    'ENABLE_EXPERIMENTAL_COREPACK=1',
  ];
  return `${lines.join('\n')}\n`;
}

export function renderGithubSecrets(v: DeployValues, s: GeneratedSecrets): string {
  const lines = [
    '# Add each line as a GitHub repo secret: Settings > Secrets and variables > Actions.',
    '# NAME is the part before the first "=", the secret value is everything after it.',
    `DATABASE_URL=${v.workerUrl}`,
    `DATABASE_URL_OWNER=${v.ownerUrl}`,
    `DATABASE_URL_DIRECT=${v.directUrl}`,
    'ODDS_PROVIDER=sgo',
    `SGO_API_KEY=${v.sgoApiKey}`,
    `ODDS_MONTHLY_BUDGET=${v.budget ?? DEFAULT_BUDGET}`,
    `BACKUP_PASSPHRASE=${s.backupPassphrase}`,
  ];
  return `${lines.join('\n')}\n`;
}
